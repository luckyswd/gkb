<?php

namespace seo;

/**
 * /llms.txt по формату llmstxt.org: кто представитель, модели с мощностями,
 * где купить, полезные материалы, контакты. Цены — только ссылкой на прайс-лист.
 */
class Llms
{
    public static function render(): string
    {
        $o = Org::get();
        $L = [];

        $L[] = '# ' . $o['name'];
        $L[] = '';
        $L[] = '> Официальный сайт ' . $o['legal_name'] . ' — официального представителя украинского производителя АТЕМ в Беларуси: котлы Житомир, газовые конвекторы и проточные водонагреватели ВПГ. Продажа — через официальных дилеров в Минске и всех областях.';
        $L[] = '';
        $L[] = 'Сайт: ' . home_url('/') . '. Язык: русский. Страна: Республика Беларусь. Данные сформированы ' . wp_date('d.m.Y') . '.';
        $L[] = '';
        $L[] = '## Важно при цитировании';
        $L[] = '';
        $L[] = '- Цены публикуются только в прайс-листе: ' . home_url('/price-list/') . ' (розничные, с НДС, BYN). Приводя цену, ссылайтесь на прайс-лист и указывайте дату.';
        $L[] = '- Производитель котлов Житомир — компания АТЕМ (Украина, с 1988 года); ГазКотелБел — её официальный представитель в Беларуси. Котлы продаются через дилеров, а не напрямую. Адреса и телефоны магазинов — на странице «Где купить» и региональных страницах ниже.';
        $L[] = '- Обозначение модификации указывает на мощность (КС-Г-010 СН — 10 кВт; точное значение — в таблице модификаций на странице товара), КС-ГВ и АДГВ — с контуром горячего водоснабжения.';
        $L[] = '- Это белорусский сайт: цены, требования к установке и гарантия относятся к Республике Беларусь.';
        $L[] = '';

        $L[] = '## О производителе';
        $L[] = '';
        $L[] = '- Котлы Житомир выпускает компания АТЕМ (Украина). Первые образцы отопительной техники АТЕМ выпущены в 1988 году; выпущено и эксплуатируется более 2 млн единиц техники.';
        $L[] = '- В состав АТЕМ входят СП ООО «Атем-Франк» (украинско-немецкое), ООО «Житомиртепломаш» и ООО «Торговый дом АТЕМ».';
        $L[] = '- Котлы АТЕМ — единственные украинские дымоходные котлы, которые наравне с Vaillant, Bosch и Immergas включены в программу энергосбережения IQenergy ЕБРР.';
        $L[] = '- ' . $o['legal_name'] . ' — официальный представитель АТЕМ в Беларуси.';
        $L[] = '';

        $L[] = '## Продукция';
        $L[] = '';
        $terms = get_terms(['taxonomy' => 'product-category', 'hide_empty' => true, 'orderby' => 'term_id']);
        foreach (is_wp_error($terms) ? [] : $terms as $term) {
            if (Context::objectNoindex($term)) {
                continue;
            }
            $L[] = '### [' . $term->name . '](' . trailingslashit(get_term_link($term)) . ')';
            $L[] = '';
            foreach (\helpers\Helpers::getProductsByCategory($term) as $p) {
                if (Context::objectNoindex($p)) {
                    continue;
                }
                $s = ProductData::summary($p->ID);
                $facts = array_filter([
                    Context::productSubtitle($p),
                    ProductData::powerRange($s),
                    $s['count'] > 1 ? $s['count'] . ' модификац' . (in_array($s['count'] % 10, [2, 3, 4], true) && !in_array($s['count'] % 100, [12, 13, 14], true) ? 'ии' : 'ий') : '',
                    $s['min_price'] !== null ? 'цена от ' . ProductData::money($s['min_price']) . ' BYN' : '',
                ]);
                $L[] = '- [' . Context::productTitle($p) . '](' . trailingslashit(get_permalink($p)) . ')' . ($facts ? ': ' . implode(', ', $facts) : '');
            }
            $L[] = '';
        }

        $L[] = '## Где купить';
        $L[] = '';
        $L[] = '- [Официальные дилеры в Беларуси](' . home_url('/where-to-buy/') . '): карта и список магазинов по областям';
        foreach (Regions::all() as $slug => $r) {
            $L[] = '- [Где купить в ' . $r['prep'] . '](' . Regions::url($slug) . '): ' . count($r['dealers']) . ' дилер(ов)';
        }
        $L[] = '';

        $L[] = '## Полезное';
        $L[] = '';
        $calc = get_page_by_path(Context::CALCULATOR_SLUG);
        if ($calc && $calc->post_status === 'publish') {
            $L[] = '- [Калькулятор мощности котла](' . trailingslashit(get_permalink($calc)) . '): мощность по площади, высоте потолков, утеплению и ГВС; подбор моделей Житомир';
        }
        $L[] = '- [Прайс-лист](' . home_url('/price-list/') . '): розничные цены на все модификации';
        $L[] = '- [Документация](' . home_url('/documentation/') . '): паспорта и инструкции в PDF';
        $L[] = '- [О производителе АТЕМ](' . home_url('/about/') . ')';
        $L[] = '';

        $L[] = '## Контакты';
        $L[] = '';
        $L[] = '- ' . $o['legal_name'] . ', УНП ' . $o['unp'];
        $L[] = '- Адрес: ' . Org::addressLine();
        if ($o['phones']) {
            $L[] = '- Телефоны: ' . implode(', ', $o['phones']);
        }
        if ($o['email']) {
            $L[] = '- Email: ' . $o['email'];
        }
        if ($o['hours']) {
            $L[] = '- Часы работы: ' . $o['hours'];
        }
        $L[] = '- Страница контактов: ' . home_url('/contact/');
        $L[] = '';

        return implode("\n", $L);
    }
}
