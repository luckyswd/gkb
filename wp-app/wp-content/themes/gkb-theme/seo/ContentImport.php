    public static function register(): void
    {
        add_action('admin_menu', static function () {
            add_management_page('Тексты категорий', 'Тексты категорий', 'manage_options', 'gkb-import-cats', [self::class, 'page']);
        });
    }

    public static function page(): void
    {
        if (!current_user_can('manage_options')) {
            return;
        }
        $log = [];
        if (isset($_POST['gkb_import']) && check_admin_referer('gkb_import_cats')) {
            foreach (self::data() as $slug => $row) {
                $term = get_term_by('slug', $slug, 'product-category');
                if (!$term) {
                    $log[] = "$slug: категория не найдена";
                    continue;
                }
                $key = 'product-category_' . $term->term_id;
                $done = [];
                if (trim(wp_strip_all_tags((string) get_field('intro_text', $key))) === '') {
                    update_field('intro_text', $row['intro_text'], $key);
                    $done[] = 'текст';
                }
                if (!array_filter((array) get_field('faq', $key))) {
                    update_field('faq', $row['faq'], $key);
                    $done[] = 'FAQ ' . count($row['faq']);
                }
                $log[] = "$slug: " . ($done ? implode(', ', $done) : 'уже заполнено, пропущено');
            }
        }
        echo '<div class="wrap"><h1>Тексты и FAQ категорий</h1>';
        if ($log) {
            echo '<div class="notice notice-success"><p>' . esc_html(implode('; ', $log)) . '</p></div>';
        }
        echo '<table class="widefat striped"><thead><tr><th>Категория</th><th>Текст сейчас</th><th>FAQ сейчас</th></tr></thead><tbody>';
        foreach (self::data() as $slug => $row) {
            $term = get_term_by('slug', $slug, 'product-category');
            $key = $term ? 'product-category_' . $term->term_id : '';
            echo '<tr><td>' . esc_html($term ? $term->name : $slug . ' — не найдена') . '</td><td>'
                . ($term ? mb_strlen(wp_strip_all_tags((string) get_field('intro_text', $key))) : 0) . ' зн.</td><td>'
                . ($term ? count(array_filter((array) get_field('faq', $key))) : 0) . '</td></tr>';
        }
        echo '</tbody></table><form method="post" style="margin-top:16px">';
        wp_nonce_field('gkb_import_cats');
        echo '<button class="button button-primary" name="gkb_import" value="1">Заполнить пустые</button></form></div>';
    }
